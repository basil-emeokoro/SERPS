def wrap_identifier(value: str, width: int = 22) -> str:
    if len(value) <= width:
        return value
    parts = value.split("_")
    lines: list[str] = []
    current = ""
    for part in parts:
        candidate = part if not current else f"{current}_{part}"
        if len(candidate) <= width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = part
    if current:
        lines.append(current)
    return "\n".join(lines)


def validate_mono_png(path: Path) -> tuple[bool, str]:
    with Image.open(path) as image:
        rgba = image.convert("RGBA")
        has_transparency = False
        coloured_pixels = 0
        sampled_pixels = 0
        for r, g, b, a in rgba.getdata():
            if a == 0:
                has_transparency = True
                continue
            if a < 255:
                has_transparency = True
            sampled_pixels += 1
            if max(r, g, b) - min(r, g, b) > 8:
                coloured_pixels += 1
        if not has_transparency:
            return False, "No transparent pixels detected"
        if sampled_pixels and coloured_pixels / sampled_pixels > 0.002:
            return False, "Detected non-monochrome coloured pixels"
    return True, "Transparent monochrome PNG"


def validate_mono_white_png(path: Path) -> tuple[bool, str]:
    with Image.open(path) as image:
        rgba = image.convert("RGBA")
        sampled_pixels = 0
        coloured_pixels = 0
        transparent_pixels = 0
        step = max(1, rgba.width * rgba.height // 6000)
        for index, (r, g, b, a) in enumerate(rgba.getdata()):
            if index % step:
                continue
            if a < 255:
                transparent_pixels += 1
            if a == 0:
                continue
            sampled_pixels += 1
            if max(r, g, b) - min(r, g, b) > 8:
                coloured_pixels += 1
        if transparent_pixels:
            return False, "Transparent pixels detected in white-background variant"
        if sampled_pixels and coloured_pixels / sampled_pixels > 0.002:
            return False, "Detected non-monochrome coloured pixels"
    return True, "White-background monochrome PNG"


