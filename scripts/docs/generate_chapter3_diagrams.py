def pipeline_shapes(items: list[str], x: int = 650, y: int = 190, w: int = 500, h: int = 70, gap: int = 25) -> list[Shape]:
    shapes: list[Shape] = []
    for i, item in enumerate(items):
        yy = y + i * (h + gap)
        fill = TEAL_LIGHT if i in {0, len(items) - 1} else WHITE
        shapes.append(Box(x, yy, w, h, item, fill=fill, title=i == 0))
        if i:
            shapes.append(Arrow(x + w / 2, yy - gap + 3, x + w / 2, yy - 4))
    return shapes


def grid_boxes(items: list[str], x: int, y: int, cols: int, box_w: int, box_h: int, gap_x: int, gap_y: int, fill: str = WHITE) -> list[Shape]:
    shapes: list[Shape] = []
    for i, item in enumerate(items):
        row, col = divmod(i, cols)
        shapes.append(Box(x + col * (box_w + gap_x), y + row * (box_h + gap_y), box_w, box_h, item, fill=fill))
    return shapes


def mmd_flow(title: str, items: Iterable[str]) -> str:
    nodes = list(items)
    lines = ["flowchart TD"]
    for i, item in enumerate(nodes):
        lines.append(f'  N{i}["{item}"]')
        if i:
            lines.append(f"  N{i-1} --> N{i}")
    return "\n".join(lines)


